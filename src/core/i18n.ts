const DICTIONARIES: Record<Lang, Record<MessageKey, string>> = { en: EN, tr: TR, ru: RU };

/** The language the settings ask for; "auto" follows the system's. */
export function lang(): Lang {
  const chosen = State.settings.language;
  if (chosen === "en" || chosen === "tr" || chosen === "ru") return chosen;
  const system = (navigator.language || "").toLowerCase();
  if (system.startsWith("tr")) return "tr";
  if (system.startsWith("ru")) return "ru";
  return "en";
}

/**
 * The tag for dates and times: the system's own (en-GB, tr-TR…) when it speaks
 * the interface language, so its date order is kept, and the bare language
 * otherwise.
 */
export function locale(): string {
  const system = navigator.language || "";
  return system.toLowerCase().startsWith(lang()) ? system : lang();
}

/**
 * `key` in the current language, with each `{name}` filled from `vars`. Without
 * `vars` the placeholders are left in, for callers that place a part themselves.
 */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const text = DICTIONARIES[lang()][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}
